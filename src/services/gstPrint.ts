import type { GstFilingRecord, GstVerificationResult } from '../../shared/gst';
import type { BusinessPartner } from '../types';

export interface GstPrintFilingHistory {
  financialYear: string;
  retrievedAt: string;
  returns: GstFilingRecord[];
}

export interface GstPrintInput {
  businessPartner: BusinessPartner;
  verification: GstVerificationResult;
  filingHistory?: GstPrintFilingHistory | null;
}

function escapeHtml(value: string | null | undefined): string {
  return (value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function display(value: string | null | undefined): string {
  return value && value.trim() ? escapeHtml(value) : 'Unavailable';
}

function formatTimestamp(value: string | null | undefined): string {
  if (!value) return 'Unavailable';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return escapeHtml(value);
  return `${date.toLocaleString()} (${escapeHtml(value)})`;
}

function row(label: string, value: string | null | undefined): string {
  return `<tr><th>${escapeHtml(label)}</th><td>${display(value)}</td></tr>`;
}

export function buildGstPrintHtml(input: GstPrintInput): string {
  const { businessPartner, verification, filingHistory } = input;
  const profile = verification.profile;

  const returnsRows = filingHistory
    ? filingHistory.returns.length > 0
      ? filingHistory.returns
          .map(
            (record) => `<tr>
              <td>${display(record.returnType)}</td>
              <td>${display(record.returnPeriod)}</td>
              <td>${display(record.filingStatus)}</td>
              <td>${display(record.filingDate)}</td>
              <td>${display(record.arn)}</td>
            </tr>`,
          )
          .join('')
      : `<tr><td colspan="5" class="empty">The provider returned no filing records for this financial year.</td></tr>`
    : `<tr><td colspan="5" class="empty">Filing history was not loaded.</td></tr>`;

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>GST data lookup - ${escapeHtml(businessPartner.bpCode)}</title>
  <style>
    body { font-family: Arial, Helvetica, sans-serif; color: #0f172a; margin: 32px; font-size: 12px; }
    h1 { font-size: 18px; margin: 0 0 4px; }
    h2 { font-size: 13px; margin: 24px 0 8px; }
    .notice { border: 2px solid #b45309; background: #fffbeb; color: #78350f; padding: 10px 12px; margin: 16px 0; font-weight: bold; }
    .meta { color: #475569; margin: 0; }
    table { width: 100%; border-collapse: collapse; margin-top: 6px; }
    th, td { border: 1px solid #cbd5e1; padding: 6px 8px; text-align: left; vertical-align: top; }
    th { width: 34%; background: #f1f5f9; }
    thead th { width: auto; }
    .empty { text-align: center; color: #64748b; font-style: italic; }
    .footer { margin-top: 28px; color: #64748b; font-size: 10px; }
  </style>
</head>
<body>
  <h1>GST data lookup - ${escapeHtml(businessPartner.bpName)}</h1>
  <p class="meta">Business Partner: ${escapeHtml(businessPartner.bpCode)} | GSTIN: ${escapeHtml(businessPartner.gstinPan || verification.gstin)}</p>

  <div class="notice">
    Third-party GST data retrieved from ${escapeHtml(verification.provider)}. This printout is not an official GST certificate,
    government document, or proof of registration. Verify details on the official GST portal before relying on them.
  </div>

  <h2>Verification record</h2>
  <table>
    ${row('Data source', verification.provider)}
    ${row('Provider endpoint', verification.endpoint)}
    ${row('Retrieved at', formatTimestamp(verification.retrievedAt))}
    ${row('GSTIN', profile.gstin)}
    ${row('Legal name', profile.legalName)}
    ${row('Trade name', profile.tradeName)}
    ${row('Registration status', profile.status)}
    ${row('Taxpayer type', profile.taxpayerType)}
    ${row('Registration date', profile.registrationDate)}
    ${row('Cancellation date', profile.cancellationDate)}
    ${row('State code', profile.stateCode)}
    ${row('Registered address', profile.address)}
    ${row('City', profile.city)}
    ${row('Pincode', profile.pincode)}
    ${row('Block status', profile.blockStatus)}
  </table>

  <h2>Filing history${filingHistory ? ` - FY ${escapeHtml(filingHistory.financialYear)}` : ''}</h2>
  <table>
    <thead>
      <tr><th>Return type</th><th>Return period</th><th>Filing status</th><th>Filing date</th><th>ARN</th></tr>
    </thead>
    <tbody>${returnsRows}</tbody>
  </table>
  ${
    filingHistory
      ? `<p class="meta">Filing history retrieved at ${formatTimestamp(filingHistory.retrievedAt)}.</p>`
      : ''
  }

  <p class="footer">Generated by the Koshit portal from the data displayed on screen. Missing values are shown as "Unavailable".</p>
</body>
</html>`;
}

export function printGstData(input: GstPrintInput): void {
  const printWindow = window.open('', '_blank');

  if (!printWindow) {
    throw new Error('The print window was blocked by the browser.');
  }

  printWindow.opener = null;
  printWindow.document.open();
  printWindow.document.write(buildGstPrintHtml(input));
  printWindow.document.close();
  printWindow.focus();
  printWindow.print();
}
