CREATE TABLE IF NOT EXISTS branch_item_availability (
  branch_availability_id VARCHAR(64) PRIMARY KEY,
  global_item_id BIGINT UNSIGNED NOT NULL,
  global_item_code VARCHAR(64) NOT NULL,
  company_id VARCHAR(64) NOT NULL,
  branch_id VARCHAR(64) NOT NULL,
  category_code VARCHAR(16) NOT NULL,
  category_name VARCHAR(120) NOT NULL,
  item_role ENUM('STOCK', 'PURCHASE', 'MANUFACTURE', 'SALES', 'SERVICE') NOT NULL DEFAULT 'PURCHASE',
  branch_purchase_uom VARCHAR(16) NULL,
  branch_inventory_uom VARCHAR(16) NULL,
  effective_purchase_uom VARCHAR(16) NOT NULL,
  effective_inventory_uom VARCHAR(16) NOT NULL,
  effective_conversion_factor DECIMAL(18,6) NOT NULL DEFAULT 1.000000,
  is_purchase_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  is_inventory_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  is_stocked BOOLEAN NOT NULL DEFAULT TRUE,
  is_manufactured BOOLEAN NOT NULL DEFAULT FALSE,
  is_sales_permitted BOOLEAN NOT NULL DEFAULT FALSE,
  is_active BOOLEAN NOT NULL DEFAULT FALSE,
  effective_from DATE NOT NULL,
  effective_to DATE NULL,
  activation_reason VARCHAR(500) NULL,
  branch_status VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
  approval_status VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
  last_audit_report_id VARCHAR(64) NULL,
  last_audit_status VARCHAR(20) NULL,
  created_by_user_id VARCHAR(64) NOT NULL,
  updated_by_user_id VARCHAR(64) NOT NULL,
  approved_by_user_id VARCHAR(64) NULL,
  approved_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_branch_item_company_branch (global_item_id, company_id, branch_id),
  KEY idx_branch_avail_scope (company_id, branch_id, category_code, is_active, approval_status),
  CONSTRAINT fk_branch_avail_global_item FOREIGN KEY (global_item_id) REFERENCES global_items(item_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
