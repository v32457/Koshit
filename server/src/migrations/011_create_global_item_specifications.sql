CREATE TABLE IF NOT EXISTS global_item_specifications (
  spec_id VARCHAR(64) PRIMARY KEY,
  item_id BIGINT UNSIGNED NOT NULL,
  default_purchase_uom VARCHAR(16) NOT NULL DEFAULT 'EA',
  default_inventory_uom VARCHAR(16) NOT NULL DEFAULT 'EA',
  conversion_numerator DECIMAL(18,6) NOT NULL DEFAULT 1.000000,
  conversion_denominator DECIMAL(18,6) NOT NULL DEFAULT 1.000000,
  conversion_factor DECIMAL(18,6) NOT NULL DEFAULT 1.000000,
  manufacturer_ref_id VARCHAR(64) NULL,
  manufacturer_name VARCHAR(150) NULL,
  brand_ref_id VARCHAR(64) NULL,
  brand_name VARCHAR(150) NULL,
  customer_part_refs_json JSON NULL,
  specifications_json JSON NULL,
  code_rule_version INT NOT NULL DEFAULT 1,
  desc_rule_version INT NOT NULL DEFAULT 1,
  last_audit_report_id VARCHAR(64) NULL,
  last_audit_status VARCHAR(20) NULL,
  is_merged BOOLEAN NOT NULL DEFAULT FALSE,
  merged_into_item_id BIGINT UNSIGNED NULL,
  created_by_user_id VARCHAR(64) NULL,
  updated_by_user_id VARCHAR(64) NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_global_spec_item (item_id),
  CONSTRAINT fk_global_spec_item FOREIGN KEY (item_id) REFERENCES global_items(item_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
