CREATE TABLE IF NOT EXISTS uom_master (
  uom_id VARCHAR(64) PRIMARY KEY,
  uom_code VARCHAR(16) NOT NULL,
  uom_name VARCHAR(100) NOT NULL,
  dimension ENUM('WEIGHT', 'VOLUME', 'COUNT', 'LENGTH', 'AREA', 'TIME', 'PACKAGING', 'OTHER') NOT NULL,
  is_base_unit BOOLEAN NOT NULL DEFAULT FALSE,
  base_unit_code VARCHAR(16) NULL,
  decimal_precision INT NOT NULL DEFAULT 2,
  allow_fractional BOOLEAN NOT NULL DEFAULT TRUE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  updated_by VARCHAR(150) NOT NULL,
  UNIQUE KEY uq_uom_master_code (uom_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
