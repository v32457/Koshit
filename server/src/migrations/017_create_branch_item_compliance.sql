CREATE TABLE IF NOT EXISTS branch_item_compliance (
  compliance_id VARCHAR(64) PRIMARY KEY,
  branch_availability_id VARCHAR(64) NOT NULL,
  shelf_life_controlled BOOLEAN NOT NULL DEFAULT FALSE,
  shelf_life_duration INT NULL,
  shelf_life_unit ENUM('DAYS', 'MONTHS', 'YEARS') NULL,
  min_remaining_shelf_life_days INT NULL,
  serial_tracking_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  serial_prefix VARCHAR(32) NULL,
  serial_format VARCHAR(64) NULL,
  warranty_applicable BOOLEAN NOT NULL DEFAULT FALSE,
  warranty_duration INT NULL,
  warranty_unit ENUM('DAYS', 'MONTHS', 'YEARS') NULL,
  warranty_terms VARCHAR(500) NULL,
  moq DECIMAL(18,4) NOT NULL DEFAULT 1,
  order_multiple DECIMAL(18,4) NOT NULL DEFAULT 1,
  service_control_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  batch_tracking_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  lot_tracking_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  quality_inspection_required BOOLEAN NOT NULL DEFAULT FALSE,
  inspection_type ENUM('RECEIVING', 'IN_PROCESS', 'PRE_DISPATCH', 'LAB_CERT') NULL,
  storage_conditions VARCHAR(255) NULL,
  regulatory_compliance VARCHAR(255) NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_branch_compliance_avail (branch_availability_id),
  CONSTRAINT fk_branch_comp_avail FOREIGN KEY (branch_availability_id) REFERENCES branch_item_availability(branch_availability_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
